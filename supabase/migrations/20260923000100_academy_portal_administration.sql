create or replace function public.current_academy_admin_organization_id()
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  actor_id uuid := auth.uid();
  organization_count integer;
  resolved_organization_id uuid;
begin
  if actor_id is null then
    raise exception using errcode = '42501', message = 'Autenticação obrigatória.';
  end if;

  select count(*), min(members.organization_id::text)::uuid
  into organization_count, resolved_organization_id
  from public.organization_members as members
  join public.organizations
    on organizations.id = members.organization_id
    and organizations.status = 'active'
  where members.user_id = actor_id
    and members.role = 'owner'
    and members.status = 'active';

  if organization_count <> 1 then
    raise exception using
      errcode = '42501',
      message = 'A administração do Portal exige exatamente um vínculo owner ativo.';
  end if;

  return resolved_organization_id;
end;
$$;

