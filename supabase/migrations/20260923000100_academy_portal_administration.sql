create or replace function public.list_academy_portal_admin_users(
  search_term text default null,
  filter_status text default null,
  filter_client_id uuid default null,
  page_size integer default 25,
  page_offset integer default 0
)
returns table (
  user_id uuid,
  full_name text,
  email text,
  email_confirmed boolean,
  auth_disabled boolean,
  portal_status text,
  organization_id uuid,
  client_id uuid,
  client_name text,
  active_location_count bigint,
  commercial_status text,
  created_at timestamptz,
  updated_at timestamptz,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  owner_organization_id uuid := public.current_academy_admin_organization_id();
  normalized_search text := lower(btrim(coalesce(search_term, '')));
  normalized_status text := nullif(btrim(coalesce(filter_status, '')), '');
  safe_page_size integer := greatest(1, least(coalesce(page_size, 25), 100));
  safe_page_offset integer := greatest(0, coalesce(page_offset, 0));
begin
  if normalized_status is not null and normalized_status not in ('pending', 'active', 'suspended') then
    raise exception using errcode = '22023', message = 'Filtro de status inválido.';
  end if;

  return query
  with visible_users as (
    select
      portal_users.user_id,
      profiles.full_name,
      auth_users.email::text,
      auth_users.email_confirmed_at is not null as email_confirmed,
      auth_users.banned_until is not null and auth_users.banned_until > now() as auth_disabled,
      portal_users.status as portal_status,
      portal_users.organization_id,
      linked_client.client_id,
      clients.name as client_name,
      coalesce(linked_client.active_location_count, 0::bigint) as active_location_count,
      commercial.status as commercial_status,
      portal_users.created_at,
      portal_users.updated_at
    from public.academy_portal_users as portal_users
    join auth.users as auth_users on auth_users.id = portal_users.user_id
    left join public.profiles on profiles.id = portal_users.user_id
    left join lateral (
      select
        coalesce(
          min(links.client_id::text) filter (where links.status = 'active'),
          min(links.client_id::text)
        )::uuid as client_id,
        count(*) filter (where links.status = 'active') as active_location_count
      from public.academy_user_locations as links
      where links.user_id = portal_users.user_id
        and links.organization_id = owner_organization_id
    ) as linked_client on true
    left join public.clients
      on clients.id = linked_client.client_id
      and clients.organization_id = owner_organization_id
    left join public.academy_portal_access as commercial
      on commercial.organization_id = owner_organization_id
      and commercial.client_id = linked_client.client_id
    where portal_users.organization_id = owner_organization_id
      or (portal_users.organization_id is null and portal_users.status = 'pending')
  )
  select
    visible_users.user_id,
    visible_users.full_name,
    visible_users.email,
    visible_users.email_confirmed,
    visible_users.auth_disabled,
    visible_users.portal_status,
    visible_users.organization_id,
    visible_users.client_id,
    visible_users.client_name,
    visible_users.active_location_count,
    visible_users.commercial_status,
    visible_users.created_at,
    visible_users.updated_at,
    count(*) over() as total_count
  from visible_users
  where (
      normalized_search = ''
      or lower(coalesce(visible_users.full_name, '')) like '%' || normalized_search || '%'
      or lower(visible_users.email) like '%' || normalized_search || '%'
    )
    and (normalized_status is null or visible_users.portal_status = normalized_status)
    and (filter_client_id is null or visible_users.client_id = filter_client_id)
  order by
    case visible_users.portal_status when 'pending' then 0 when 'suspended' then 1 else 2 end,
    visible_users.created_at desc,
    visible_users.user_id
  limit safe_page_size
  offset safe_page_offset;
end;
$$;

