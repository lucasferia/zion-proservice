create or replace function public.current_academy_request_scope(target_client_location_id uuid)
returns table (organization_id uuid, client_id uuid, client_location_id uuid, location_name text)
language sql stable security definer set search_path = '' as $$
  select scope.organization_id, scope.client_id, scope.client_location_id, scope.location_name
  from public.current_academy_equipment_scope(target_client_location_id) scope;
$$;

create or replace function public.maintenance_request_scope_is_current(target_request_id uuid, target_location_id uuid, target_actor_id uuid)
returns boolean language plpgsql stable security definer set search_path = '' as $$
begin
  return exists (
    select 1 from public.maintenance_requests requests
    join public.current_academy_request_scope(target_location_id) scope
      on scope.organization_id = requests.organization_id and scope.client_id = requests.client_id
      and scope.client_location_id = requests.client_location_id
    join public.equipment equipment on equipment.id = requests.equipment_id
      and equipment.organization_id = requests.organization_id and equipment.client_id = requests.client_id
      and equipment.client_location_id = requests.client_location_id and equipment.deleted_at is null
    where requests.id = target_request_id and requests.requested_by = target_actor_id
  );
exception
  when sqlstate '42501' then
    return false;
end;
$$;

create or replace function public.is_internal_maintenance_request_member(target_organization_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null
    and not exists (
      select 1
      from public.academy_portal_users as portal_users
      where portal_users.user_id = auth.uid()
    )
    and exists (
      select 1
      from public.organization_members as members
      where members.organization_id = target_organization_id
        and members.user_id = auth.uid()
        and members.role in ('owner', 'technician')
        and members.status = 'active'
    );
$$;

create or replace function public.can_access_maintenance_request(target_request_id uuid, target_location_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null
    and public.maintenance_request_scope_is_current(target_request_id, target_location_id, auth.uid());
$$;

create or replace function public.portal_create_maintenance_request(
  target_client_location_id uuid, target_equipment_id uuid, request_title text,
  request_description text, request_criticality text, request_submission_key uuid
) returns uuid language plpgsql security definer set search_path = '' as $$
declare actor_id uuid := auth.uid(); scope_record record; new_id uuid; existing_id uuid;
begin
  if request_submission_key is null then raise exception using errcode = '22023', message = 'Identificador de envio invalido.'; end if;
  select * into scope_record from public.current_academy_request_scope(target_client_location_id);
  if not exists (select 1 from public.equipment e where e.id = target_equipment_id
    and e.organization_id = scope_record.organization_id and e.client_id = scope_record.client_id
    and e.client_location_id = scope_record.client_location_id and e.deleted_at is null and e.status <> 'inactive') then
    raise exception using errcode = '42501', message = 'Equipamento indisponivel nesta unidade.';
  end if;
  if char_length(btrim(coalesce(request_title,''))) not between 5 and 160 then raise exception using errcode='22023', message='Informe um titulo entre 5 e 160 caracteres.'; end if;
  if char_length(btrim(coalesce(request_description,''))) not between 10 and 4000 then raise exception using errcode='22023', message='Informe uma descricao entre 10 e 4000 caracteres.'; end if;
  if request_criticality not in ('low','medium','high','critical') then raise exception using errcode='22023', message='Criticidade percebida invalida.'; end if;
  select id into existing_id from public.maintenance_requests where requested_by=actor_id and submission_key=request_submission_key;
  if existing_id is not null then return existing_id; end if;
  insert into public.maintenance_requests (organization_id,client_id,client_location_id,equipment_id,requested_by,submission_key,title,description,reported_criticality)
  values (scope_record.organization_id,scope_record.client_id,scope_record.client_location_id,target_equipment_id,actor_id,request_submission_key,btrim(request_title),btrim(request_description),request_criticality)
  returning id into new_id;
  insert into public.maintenance_request_events (organization_id,maintenance_request_id,action,actor_id)
  values (scope_record.organization_id,new_id,'request_created',actor_id);
  return new_id;
exception when unique_violation then
  select id into existing_id from public.maintenance_requests where requested_by=actor_id and submission_key=request_submission_key;
  if existing_id is not null then return existing_id; end if; raise;
end;
$$;

create or replace function public.portal_list_maintenance_requests(
  target_client_location_id uuid, search_term text default null, filter_status text default null,
  filter_criticality text default null, page_number integer default 1, page_size integer default 12
) returns table (id uuid,title text,description text,reported_criticality text,status text,equipment_id uuid,equipment_name text,created_at timestamptz,total_count bigint)
language plpgsql stable security definer set search_path = '' as $$
declare actor_id uuid:=auth.uid(); scope_record record; q text:=nullif(btrim(coalesce(search_term,'')),''); p int:=greatest(coalesce(page_number,1),1); s int:=least(greatest(coalesce(page_size,12),1),50);
begin
  select * into scope_record from public.current_academy_request_scope(target_client_location_id);
  return query select r.id,r.title,r.description,r.reported_criticality,r.status,r.equipment_id,e.name,r.created_at,count(*) over()::bigint
  from public.maintenance_requests r join public.equipment e on e.id=r.equipment_id and e.organization_id=r.organization_id
  where r.organization_id=scope_record.organization_id and r.client_id=scope_record.client_id and r.client_location_id=scope_record.client_location_id
    and r.requested_by=actor_id and (q is null or r.title ilike '%'||q||'%' or e.name ilike '%'||q||'%')
    and (nullif(filter_status,'') is null or r.status=filter_status) and (nullif(filter_criticality,'') is null or r.reported_criticality=filter_criticality)
  order by r.created_at desc,r.id limit s offset (p-1)*s;
end;
$$;

