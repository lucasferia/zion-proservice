create or replace function public.portal_cancel_maintenance_request(target_client_location_id uuid,target_request_id uuid,cancel_reason text)
returns void language plpgsql security definer set search_path = '' as $$
declare actor_id uuid:=auth.uid(); scope_record record; current_status text;
begin
  select * into scope_record from public.current_academy_request_scope(target_client_location_id);
  if char_length(btrim(coalesce(cancel_reason,''))) not between 3 and 500 then raise exception using errcode='22023',message='Informe um motivo entre 3 e 500 caracteres.'; end if;
  select status into current_status from public.maintenance_requests where id=target_request_id and organization_id=scope_record.organization_id
    and client_id=scope_record.client_id and client_location_id=scope_record.client_location_id and requested_by=actor_id for update;
  if not found then raise exception using errcode='42501',message='Solicitacao indisponivel.'; end if;
  if current_status='cancelled' then return; end if;
  if current_status<>'pending' then raise exception using errcode='42501',message='Somente solicitacoes pendentes podem ser canceladas.'; end if;
  update public.maintenance_requests set status='cancelled',cancellation_reason=btrim(cancel_reason),cancelled_at=now(),cancelled_by=actor_id,updated_at=now() where id=target_request_id;
  insert into public.maintenance_request_events(organization_id,maintenance_request_id,action,actor_id,details)
  values(scope_record.organization_id,target_request_id,'request_cancelled',actor_id,jsonb_build_object('reason',btrim(cancel_reason)))
  on conflict (maintenance_request_id) where action = 'request_cancelled' do nothing;
end;
$$;

create or replace function public.portal_register_maintenance_request_photo(target_client_location_id uuid,target_request_id uuid,target_storage_path text,target_mime_type text,target_file_size bigint,target_sort_order integer)
returns uuid language plpgsql security definer set search_path = '' as $$
declare actor_id uuid:=auth.uid(); scope_record record; photo_id uuid;
begin
  select * into scope_record from public.current_academy_request_scope(target_client_location_id);
  perform 1 from public.maintenance_requests r where r.id=target_request_id and r.organization_id=scope_record.organization_id and r.client_location_id=scope_record.client_location_id and r.requested_by=actor_id and r.status='pending' for update;
  if not found then raise exception using errcode='42501',message='Fotos so podem ser adicionadas a uma solicitacao pendente.'; end if;
  if not public.maintenance_request_scope_is_current(target_request_id,target_client_location_id,actor_id) then raise exception using errcode='42501',message='Acesso a solicitacao indisponivel.'; end if;
  if target_mime_type not in ('image/webp','image/jpeg') or target_file_size not between 1 and 10485760 or target_sort_order not between 0 and 4 then raise exception using errcode='22023',message='Metadados da foto invalidos.'; end if;
  if target_storage_path <> scope_record.organization_id::text||'/'||target_request_id::text||'/'||actor_id::text||'/'||split_part(target_storage_path,'/',4) or split_part(target_storage_path,'/',4)='' then raise exception using errcode='22023',message='Caminho da foto invalido.'; end if;
  if not exists(select 1 from storage.objects where bucket_id='maintenance-request-photos' and name=target_storage_path and owner_id=actor_id::text) then raise exception using errcode='23503',message='Arquivo privado nao encontrado no Storage.'; end if;
  if (select count(*) from public.maintenance_request_photos where maintenance_request_id=target_request_id and removed_at is null)>=5 then raise exception using errcode='23514',message='Cada solicitacao aceita no maximo 5 fotos.'; end if;
  insert into public.maintenance_request_photos(organization_id,maintenance_request_id,storage_path,mime_type,file_size,sort_order,created_by)
  values(scope_record.organization_id,target_request_id,target_storage_path,target_mime_type,target_file_size,target_sort_order,actor_id) returning id into photo_id;
  insert into public.maintenance_request_events(organization_id,maintenance_request_id,action,actor_id,details) values(scope_record.organization_id,target_request_id,'photo_added',actor_id,jsonb_build_object('photo_id',photo_id));
  return photo_id;
end;
$$;

