create or replace function public.portal_remove_maintenance_request_photo(target_client_location_id uuid,target_request_id uuid,target_photo_id uuid)
returns text language plpgsql security definer set search_path = '' as $$
declare actor_id uuid:=auth.uid(); scope_record record; result_path text; current_status text;
begin
  select * into scope_record from public.current_academy_request_scope(target_client_location_id);
  select status into current_status from public.maintenance_requests where id=target_request_id and organization_id=scope_record.organization_id and client_location_id=scope_record.client_location_id and requested_by=actor_id for update;
  if not found or current_status<>'pending' then raise exception using errcode='42501',message='Fotos so podem ser removidas de uma solicitacao pendente.'; end if;
  select storage_path into result_path from public.maintenance_request_photos where id=target_photo_id and maintenance_request_id=target_request_id and organization_id=scope_record.organization_id and created_by=actor_id;
  if not found then raise exception using errcode='42501',message='Foto indisponivel.'; end if;
  update public.maintenance_request_photos set removed_at=coalesce(removed_at,now()),removed_by=coalesce(removed_by,actor_id) where id=target_photo_id;
  if not exists(select 1 from public.maintenance_request_events where maintenance_request_id=target_request_id and action='photo_removed' and details->>'photo_id'=target_photo_id::text) then
    insert into public.maintenance_request_events(organization_id,maintenance_request_id,action,actor_id,details) values(scope_record.organization_id,target_request_id,'photo_removed',actor_id,jsonb_build_object('photo_id',target_photo_id));
