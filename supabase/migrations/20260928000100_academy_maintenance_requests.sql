create or replace function public.can_delete_maintenance_request_photo_object(object_name text)
returns boolean language plpgsql volatile security definer set search_path='' as $$
declare
  actor_id uuid := auth.uid();
  path_parts text[] := string_to_array(object_name, '/');
  request_record record;
  photo_record record;
begin
  if actor_id is null
    or object_name is null
    or cardinality(path_parts) <> 4
    or path_parts[1] = ''
    or path_parts[2] = ''
    or path_parts[3] = ''
    or path_parts[4] = ''
    or object_name <> path_parts[1] || '/' || path_parts[2] || '/' || path_parts[3] || '/' || path_parts[4]
  then
    return false;
  end if;

  select requests.id, requests.organization_id, requests.requested_by
  into request_record
  from public.maintenance_requests as requests
  where requests.organization_id::text = path_parts[1]
    and requests.id::text = path_parts[2]
    and requests.requested_by = actor_id
    and requests.requested_by::text = path_parts[3]
  for update;

  if not found then
    return false;
  end if;

  if not exists (
    select 1
    from storage.objects as objects
    where objects.bucket_id = 'maintenance-request-photos'
      and objects.name = object_name
      and objects.owner_id = actor_id::text
  ) then
    return false;
  end if;

  select photos.organization_id, photos.maintenance_request_id, photos.created_by,
    photos.removed_at, photos.removed_by
  into photo_record
  from public.maintenance_request_photos as photos
  where photos.bucket_id = 'maintenance-request-photos'
    and photos.storage_path = object_name;

  if not found then
    -- Compensacao de upload proprio ainda sem metadado. O lock da solicitacao
    -- serializa esta decisao com portal_register_maintenance_request_photo().
    return true;
  end if;

  -- Uma foto vinculada so pode ser removida depois do tombstone emitido pela RPC.
  return photo_record.organization_id = request_record.organization_id
    and photo_record.maintenance_request_id = request_record.id
    and photo_record.created_by = actor_id
    and photo_record.removed_at is not null
    and photo_record.removed_by = actor_id;
end;
$$;

