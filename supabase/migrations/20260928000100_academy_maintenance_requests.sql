  join public.clients c on c.id=r.client_id and c.organization_id=r.organization_id join public.client_locations l on l.id=r.client_location_id and l.organization_id=r.organization_id
  join public.profiles on profiles.id=r.requested_by where r.organization_id=target_organization_id
